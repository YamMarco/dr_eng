// Generates the student shell's content indexes, so the shell never carries the content itself:
// - src/lib/content/meta.generated.ts: every lesson without its screens (id, section, position,
//   prerequisites, round count, "has content", "has a writing task"); screens load per lesson file.
// - src/lib/quiz/meta.generated.ts: every exam without its parts; an exam loads when its page opens.
// - src/lib/deck/meta.generated.ts: every word list's word ids; the words load on the words page.
// Run by the Vite plugin (build start + on content edits) and by `npm run check` / `npm test`
// through `prepare`; `node scripts/lesson-meta.mjs` runs it by hand.
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../src/lib/content/', import.meta.url);
const quizRoot = new URL('../src/lib/quiz/', import.meta.url);

/** Every section file and the name it exports; the order is the path's lesson order. */
export const SECTION_FILES = [
	['c/c-1', 'c1Lessons'],
	['c/c-2', 'c2Lessons'],
	['c/c-3', 'c3Lessons'],
	['d/d-1', 'd1Lessons'],
	['d/d-2', 'd2Lessons'],
	['d/d-3', 'd3Lessons'],
	['d/d-4', 'd4Lessons'],
	['d/d-5', 'd5Lessons'],
	['e/e-1', 'e1Lessons'],
	['f/f-1', 'f1Lessons'],
	['f/f-2', 'f2Lessons'],
	['f/f-3', 'f3Lessons'],
	['g/g-1', 'g1Lessons'],
	['g/g-2', 'g2Lessons'],
	['cobe/cobe-1', 'cobe1Lessons'],
	['cobe/cobe-2', 'cobe2Lessons'],
	['cobe/cobe-3', 'cobe3Lessons']
];

/** Every exam file (lib/quiz/<file>/index.ts) and the name it exports, in list order. */
export const QUIZ_FILES = [
	['c', 'cQuizzes'],
	['e', 'eQuizzes'],
	['g', 'gQuizzes'],
	['cobe', 'cobeQuizzes']
];

/** Every word list: module, deck id (progress key), label, list file (under content/), export. */
export const DECK_FILES = [
	['e', 'e-a', '1', 'e/list-a', 'listA'],
	['e', 'e-b', '2', 'e/list-b', 'listB'],
	['e', 'e-c', '3', 'e/list-c', 'listC'],
	['e', 'e-d', '4', 'e/list-d', 'listD']
];

/** @param {string} bust a cache-buster, so a rerun in a long-lived process sees edited files */
export async function buildLessonMeta(bust = '') {
	const { isScreenEmpty } = await import(
		new URL('../src/lib/lesson-screens/types.ts', import.meta.url).href
	);
	const meta = [];
	for (const [file, name] of SECTION_FILES) {
		const mod = await import(new URL(`${file}.ts`, root).href + (bust ? `?t=${bust}` : ''));
		for (const l of mod[name]) {
			const screens = [
				l.content.preface,
				...l.content.rounds.map((/** @type {any} */ r) => r.screens)
			];
			meta.push({
				id: l.id,
				file,
				section: l.section,
				...(l.titleEn !== undefined && { titleEn: l.titleEn }),
				required: l.required,
				position: l.position,
				...(l.requiredRounds !== undefined && { requiredRounds: l.requiredRounds }),
				big: l.big,
				...(l.image !== undefined && { image: l.image }),
				rounds: l.content.rounds.length,
				ready: screens.some((/** @type {any[]} */ s) =>
					s.some((/** @type {any} */ x) => !isScreenEmpty(x))
				),
				writing: screens.some((/** @type {any[]} */ s) =>
					s.some((/** @type {any} */ x) => x.type === 'writing-task')
				)
			});
		}
	}
	return meta;
}

/** @param {string} bust */
export async function buildQuizMeta(bust = '') {
	const meta = [];
	for (const [file, name] of QUIZ_FILES) {
		const mod = await import(
			new URL(`${file}/index.ts`, quizRoot).href + (bust ? `?t=${bust}` : '')
		);
		for (const q of mod[name])
			meta.push({
				id: q.id,
				uuid: q.uuid,
				moduleId: q.module,
				file,
				kind: q.kind,
				...(q.kind === 'ministry' && { year: q.year ?? 0 })
			});
	}
	return meta;
}

/** @param {string} bust */
export async function buildDeckMeta(bust = '') {
	/** @type {Record<string, object[]>} */
	const decks = {};
	for (const [moduleId, id, letter, file, name] of DECK_FILES) {
		const mod = await import(new URL(`${file}.ts`, root).href + (bust ? `?t=${bust}` : ''));
		const wordIds = mod[name].map((/** @type {{ id: string }} */ w) => w.id);
		(decks[moduleId] ??= []).push({ id: id, letter, wordIds });
	}
	return decks;
}

const HEADER =
	'// GENERATED by scripts/lesson-meta.mjs from the content files: do not edit, not committed.';
const rows = (/** @type {object[]} */ list) => list.map((m) => JSON.stringify(m)).join(',\n\t');

/** @param {object[]} meta */
export function renderLessonMeta(meta) {
	return `${HEADER}
import type { LessonMeta } from './meta';

export const lessonMeta: LessonMeta[] = [
	${rows(meta)}
];
`;
}

/** @param {object[]} meta */
export function renderQuizMeta(meta) {
	return `${HEADER}
import type { Quiz } from '../quizzes';

export const quizMeta: Quiz[] = [
	${rows(meta)}
];
`;
}

/** @param {Record<string, object[]>} decks */
export function renderDeckMeta(decks) {
	return `${HEADER}
import type { Deck } from './index';

export const deckMeta: Record<string, Deck[]> = ${JSON.stringify(decks)};
`;
}

/** Writes a file when its content changed (an unchanged write would retrigger the dev server). */
function write(/** @type {URL} */ url, /** @type {string} */ text) {
	const path = fileURLToPath(url);
	if (existsSync(path) && readFileSync(path, 'utf8') === text) return false;
	writeFileSync(path, text);
	return true;
}

/** Writes all three indexes; true when any changed. */
export async function writeContentMeta(bust = '') {
	const changed = [
		write(new URL('meta.generated.ts', root), renderLessonMeta(await buildLessonMeta(bust))),
		write(new URL('meta.generated.ts', quizRoot), renderQuizMeta(await buildQuizMeta(bust))),
		write(new URL('../deck/meta.generated.ts', quizRoot), renderDeckMeta(await buildDeckMeta(bust)))
	];
	return changed.some(Boolean);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	console.log((await writeContentMeta()) ? 'content meta written' : 'content meta unchanged');
}
