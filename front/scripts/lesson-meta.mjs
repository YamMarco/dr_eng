// Generates src/lib/content/meta.generated.ts: every lesson without its screens (id, section,
// position, prerequisites, round count, "has content", "has a writing task"). The student shell
// (home, module page, lesson path) reads this instead of the lesson content, which is ~1 MB and
// loads only when a lesson opens. Run by the Vite plugin (build start + on content edits) and by
// `npm run check` / `npm test` through `prepare`; `node scripts/lesson-meta.mjs` runs it by hand.
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../src/lib/content/', import.meta.url);
const out = new URL('meta.generated.ts', root);

/** Every section file and the name it exports; the order is the path's lesson order. */
export const SECTION_FILES = [
	['c/c-1', 'c1Lessons'],
	['c/c-2', 'c2Lessons'],
	['c/c-3', 'c3Lessons'],
	['d/d-1', 'd1Lessons'],
	['d/d-2', 'd2Lessons'],
	['d/d-3', 'd3Lessons'],
	['d/d-4', 'd4Lessons'],
	['d/d-5', 'd5Lessons'],
	['e/e-1', 'e1Lessons'],
	['f/f-1', 'f1Lessons'],
	['f/f-2', 'f2Lessons'],
	['f/f-3', 'f3Lessons'],
	['g/g-1', 'g1Lessons'],
	['g/g-2', 'g2Lessons'],
	['cobe/cobe-1', 'cobe1Lessons'],
	['cobe/cobe-2', 'cobe2Lessons'],
	['cobe/cobe-3', 'cobe3Lessons']
];

/** @param {string} bust a cache-buster, so a rerun in a long-lived process sees edited files */
export async function buildLessonMeta(bust = '') {
	const { isScreenEmpty } = await import(
		new URL('../src/lib/lesson-screens/types.ts', import.meta.url).href
	);
	const meta = [];
	for (const [file, name] of SECTION_FILES) {
		const mod = await import(new URL(`${file}.ts`, root).href + (bust ? `?t=${bust}` : ''));
		for (const l of mod[name]) {
			const screens = [
				l.content.preface,
				...l.content.rounds.map((/** @type {any} */ r) => r.screens)
			];
			meta.push({
				id: l.id,
				file,
				section: l.section,
				...(l.titleEn !== undefined && { titleEn: l.titleEn }),
				required: l.required,
				position: l.position,
				...(l.requiredRounds !== undefined && { requiredRounds: l.requiredRounds }),
				big: l.big,
				...(l.image !== undefined && { image: l.image }),
				rounds: l.content.rounds.length,
				ready: screens.some((/** @type {any[]} */ s) =>
					s.some((/** @type {any} */ x) => !isScreenEmpty(x))
				),
				writing: screens.some((/** @type {any[]} */ s) =>
					s.some((/** @type {any} */ x) => x.type === 'writing-task')
				)
			});
		}
	}
	return meta;
}

/** @param {object[]} meta */
export function renderLessonMeta(meta) {
	return `// GENERATED by scripts/lesson-meta.mjs from the lesson files: do not edit, not committed.
import type { LessonMeta } from './meta';

export const lessonMeta: LessonMeta[] = [
	${meta.map((m) => JSON.stringify(m)).join(',\n\t')}
];
`;
}

/** Writes the file when its content changed (an unchanged write would retrigger the dev server). */
export async function writeLessonMeta(bust = '') {
	const text = renderLessonMeta(await buildLessonMeta(bust));
	const path = fileURLToPath(out);
	if (existsSync(path) && readFileSync(path, 'utf8') === text) return false;
	writeFileSync(path, text);
	return true;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	console.log((await writeLessonMeta()) ? 'lesson meta written' : 'lesson meta unchanged');
}
